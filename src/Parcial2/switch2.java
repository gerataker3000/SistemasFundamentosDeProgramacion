package Parcial2;

public class switch2 {
    public static void main(String[] args) {
        int seleccion = 2;
        switch (seleccion){
            case 1:
                System.out.println("Viernes 13");
                System.out.println("Japonas");
                break;
            case 2:
                System.out.println("La idea de ti");
                System.out.println("Si yo tuviera 30");
                System.out.println("La pelicuala");
                System.out.println("Votos de amor");
                break;
            default:
                System.out.println("Terror bajo la tierra");
                break;
        }
    }
}
